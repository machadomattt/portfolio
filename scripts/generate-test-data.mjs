// Regenerates src/data/testRuns.ts from a Playwright JSON report.
// Run: npm run test:report
import { readFileSync, writeFileSync } from 'node:fs'
import { flattenReport, summarize } from './lib/flatten-report.mjs'

const reportPath = process.argv[2] ?? 'test-results/results.json'
const outPath = 'src/data/testRuns.ts'

const report = JSON.parse(readFileSync(reportPath, 'utf8'))
const tests = flattenReport(report)
const meta = summarize(report, tests)

const banner = '// Auto-generated by scripts/generate-test-data.mjs — do not edit by hand.\n// Regenerate with: npm run test:report\n'

const body = `${banner}
export interface TestResult {
  describe: string
  title: string
  file: string
  status: 'passed' | 'failed' | 'skipped' | 'unknown'
  duration: number
  error?: string
  skipReason?: string
}

export interface TestRunMeta {
  generatedAt: string
  durationMs: number
  total: number
  passed: number
  failed: number
  skipped: number
}

export const testRunMeta: TestRunMeta = ${JSON.stringify(meta, null, 2)}

export const testResults: TestResult[] = ${JSON.stringify(tests, null, 2)}
`

writeFileSync(outPath, body)
console.log(`Wrote ${tests.length} test results to ${outPath}`)
